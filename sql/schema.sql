-- Cricbuzz LiveStats
-- PostgreSQL schema for development.
-- Run against the cricbuzz_livestats database.
-- This script creates missing tables and indexes; it does not delete existing data.

BEGIN;

CREATE TABLE IF NOT EXISTS roles (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    email_verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_lower
    ON users (LOWER(email));

CREATE TABLE IF NOT EXISTS user_roles (
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES roles(role_id) ON DELETE CASCADE,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS email_verification_challenges (
    challenge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    otp_hash TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    verified_at TIMESTAMPTZ,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_email_challenges_email_created
    ON email_verification_challenges (LOWER(email), created_at DESC);

CREATE TABLE IF NOT EXISTS user_sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_user_sessions_user
    ON user_sessions (user_id);

CREATE TABLE IF NOT EXISTS teams (
    team_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_name VARCHAR(120) NOT NULL UNIQUE,
    country VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS players (
    player_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(160) NOT NULL,
    date_of_birth DATE,
    country VARCHAR(100),
    batting_style VARCHAR(80),
    bowling_style VARCHAR(100),
    playing_role VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_players_full_name
    ON players (LOWER(full_name));

CREATE TABLE IF NOT EXISTS player_teams (
    player_id BIGINT NOT NULL REFERENCES players(player_id) ON DELETE CASCADE,
    team_id BIGINT NOT NULL REFERENCES teams(team_id) ON DELETE CASCADE,
    team_role VARCHAR(80),
    start_date DATE,
    end_date DATE,
    PRIMARY KEY (player_id, team_id, start_date)
);

CREATE TABLE IF NOT EXISTS venues (
    venue_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_name VARCHAR(180) NOT NULL,
    city VARCHAR(120),
    country VARCHAR(100),
    UNIQUE (venue_name, city, country)
);

CREATE TABLE IF NOT EXISTS series (
    series_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_name VARCHAR(200) NOT NULL,
    start_date DATE,
    end_date DATE,
    UNIQUE (series_name, start_date)
);

CREATE TABLE IF NOT EXISTS match_formats (
    format_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    format_name VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS matches (
    match_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_match_id VARCHAR(80) UNIQUE,
    description VARCHAR(200) NOT NULL,
    series_id BIGINT REFERENCES series(series_id) ON DELETE SET NULL,
    venue_id BIGINT REFERENCES venues(venue_id) ON DELETE SET NULL,
    format_id BIGINT REFERENCES match_formats(format_id) ON DELETE SET NULL,
    team1_id BIGINT REFERENCES teams(team_id) ON DELETE SET NULL,
    team2_id BIGINT REFERENCES teams(team_id) ON DELETE SET NULL,
    status VARCHAR(80) NOT NULL DEFAULT 'Scheduled',
    start_time TIMESTAMPTZ,
    winner_team_id BIGINT REFERENCES teams(team_id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (team1_id IS NULL OR team2_id IS NULL OR team1_id <> team2_id)
);

CREATE INDEX IF NOT EXISTS idx_matches_start_time
    ON matches (start_time DESC);

CREATE TABLE IF NOT EXISTS batting_stats (
    batting_stat_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
    player_id BIGINT NOT NULL REFERENCES players(player_id) ON DELETE CASCADE,
    team_id BIGINT REFERENCES teams(team_id) ON DELETE SET NULL,
    innings_number SMALLINT NOT NULL DEFAULT 1 CHECK (innings_number > 0),
    runs INTEGER NOT NULL DEFAULT 0 CHECK (runs >= 0),
    balls_faced INTEGER NOT NULL DEFAULT 0 CHECK (balls_faced >= 0),
    fours INTEGER NOT NULL DEFAULT 0 CHECK (fours >= 0),
    sixes INTEGER NOT NULL DEFAULT 0 CHECK (sixes >= 0),
    is_not_out BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (match_id, player_id, innings_number)
);

CREATE INDEX IF NOT EXISTS idx_batting_stats_player
    ON batting_stats (player_id);

CREATE TABLE IF NOT EXISTS bowling_stats (
    bowling_stat_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
    player_id BIGINT NOT NULL REFERENCES players(player_id) ON DELETE CASCADE,
    team_id BIGINT REFERENCES teams(team_id) ON DELETE SET NULL,
    innings_number SMALLINT NOT NULL DEFAULT 1 CHECK (innings_number > 0),
    overs_bowled NUMERIC(5,1) NOT NULL DEFAULT 0 CHECK (overs_bowled >= 0),
    legal_balls INTEGER NOT NULL DEFAULT 0 CHECK (legal_balls >= 0),
    runs_conceded INTEGER NOT NULL DEFAULT 0 CHECK (runs_conceded >= 0),
    wickets INTEGER NOT NULL DEFAULT 0 CHECK (wickets >= 0),
    maidens INTEGER NOT NULL DEFAULT 0 CHECK (maidens >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (match_id, player_id, innings_number)
);

CREATE INDEX IF NOT EXISTS idx_bowling_stats_player
    ON bowling_stats (player_id);

CREATE TABLE IF NOT EXISTS match_innings (
    innings_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
    innings_number SMALLINT NOT NULL CHECK (innings_number > 0),
    batting_team_id BIGINT REFERENCES teams(team_id) ON DELETE SET NULL,
    runs INTEGER NOT NULL DEFAULT 0 CHECK (runs >= 0),
    wickets INTEGER NOT NULL DEFAULT 0 CHECK (wickets >= 0),
    overs NUMERIC(5,1) NOT NULL DEFAULT 0 CHECK (overs >= 0),
    extras INTEGER NOT NULL DEFAULT 0 CHECK (extras >= 0),
    UNIQUE (match_id, innings_number)
);

INSERT INTO roles (role_name, description)
VALUES
    ('user', 'Standard application user'),
    ('admin', 'Application administrator')
ON CONFLICT (role_name) DO NOTHING;

INSERT INTO match_formats (format_name)
VALUES ('Test'), ('ODI'), ('T20'), ('IPL'), ('T10')
ON CONFLICT (format_name) DO NOTHING;

COMMIT;
